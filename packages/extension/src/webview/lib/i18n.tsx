/** Non-hook accessor for code that runs outside the React render tree (e.g. a message-event handler closure). Prefer `useI18n()` inside components. */
export function getDict(lang: Lang): typeof EN {
  return lang === 'vi' ? VI : EN;
}

const I18nContext = createContext<typeof EN>(EN);

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  return <I18nContext.Provider value={getDict(lang)}>{children}</I18nContext.Provider>;
}

export function useI18n(): typeof EN {
  return useContext(I18nContext);
}
